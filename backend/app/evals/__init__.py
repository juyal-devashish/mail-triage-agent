"""
Score triage on the SYNTHETIC inbox against its answer key. Only this package and the tests read the key.

The costly mistake is hiding something that needs you, so the headline numbers are:

* needs-you recall: of the emails that need you, how many the dashboard puts in Needs you.
* hidden: emails that need you but land in Noise (folded away in a digest). This should be zero.
* noise precision: of what the dashboard calls noise, how much really is.

Scored on the final verdicts the user sees (after code-side rules), from stored responses only.
"""

from collections import Counter
from dataclasses import dataclass, field

from app.domain.types import BUCKETS, Bucket, Message, Truth
from app.domain.verdict import decide
from app.llm.triage_llm import ResponseCache, triage


@dataclass
class EvalResult:
    total: int
    answered: int
    statuses: dict[str, int]
    confusion: dict[tuple[Bucket, Bucket], int]  # (truth, predicted) -> count
    category_correct: int
    hidden: list[tuple[str, str, str]] = field(default_factory=list)  # (id, subject, predicted) needs_you -> noise
    misses: list[tuple[str, str, Bucket, Bucket, str]] = field(default_factory=list)  # id, subject, truth, pred, note
    tricky: list[tuple[str, Bucket, Bucket, bool]] = field(default_factory=list)  # note, truth, pred, ok

    def count(self, truth: Bucket | None = None, pred: Bucket | None = None) -> int:
        return sum(
            n for (t, p), n in self.confusion.items() if (truth is None or t == truth) and (pred is None or p == pred)
        )

    @property
    def accuracy(self) -> float:
        return sum(self.confusion.get((b, b), 0) for b in BUCKETS) / max(1, self.total)

    @property
    def needs_recall(self) -> float:
        return self.confusion.get(("needs_you", "needs_you"), 0) / max(1, self.count(truth="needs_you"))

    @property
    def needs_precision(self) -> float:
        return self.confusion.get(("needs_you", "needs_you"), 0) / max(1, self.count(pred="needs_you"))

    @property
    def noise_precision(self) -> float:
        return self.confusion.get(("noise", "noise"), 0) / max(1, self.count(pred="noise"))


def evaluate(
    messages: list[Message], key: dict[str, Truth], cache: ResponseCache, *, model: str, effort: str, max_tokens: int
) -> EvalResult:
    summary = triage(messages, None, cache, model=model, effort=effort, max_tokens=max_tokens, max_calls=0)
    confusion: Counter[tuple[Bucket, Bucket]] = Counter()
    result = EvalResult(
        total=len(messages),
        answered=sum(1 for a in summary.answers.values() if a is not None),
        statuses=summary.counts(),
        confusion={},
        category_correct=0,
    )
    for m in messages:
        truth = key[m.id]
        answer = summary.answers.get(m.id)
        v = decide(m, answer, [])
        confusion[(truth.bucket, v.bucket)] += 1
        if answer is not None and answer.category == truth.category:
            result.category_correct += 1
        if truth.bucket != v.bucket:
            result.misses.append((m.id, m.subject, truth.bucket, v.bucket, truth.note))
        if truth.bucket == "needs_you" and v.bucket == "noise":
            result.hidden.append((m.id, m.subject, v.bucket))
        if truth.note:
            result.tricky.append((truth.note, truth.bucket, v.bucket, truth.bucket == v.bucket))
    result.confusion = dict(confusion)
    return result


def pct(x: float) -> str:
    return f"{x * 100:.0f}%"


def report(r: EvalResult, model: str, effort: str) -> str:
    lines = [
        "# Results",
        "",
        "Generated by `python -m app.cli eval --write` from stored responses. Don't edit by hand.",
        "",
        f"Triage of the **SYNTHETIC** inbox ({r.total} emails) by `{model}` at effort `{effort}`, scored against "
        "the answer key on the verdicts the dashboard shows (after code-side rules, with no sender rules).",
        "",
        f"Answered: {r.answered} of {r.total}. Attempt statuses: "
        + ", ".join(f"{k} {v}" for k, v in sorted(r.statuses.items()))
        + ".",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Needs-you recall | {pct(r.needs_recall)} ({r.confusion.get(('needs_you', 'needs_you'), 0)} of "
        f"{r.count(truth='needs_you')}) |",
        f"| Needs-you precision | {pct(r.needs_precision)} |",
        f"| Hidden (needs you, shown as noise) | {len(r.hidden)} |",
        f"| Noise precision | {pct(r.noise_precision)} |",
        f"| Bucket accuracy | {pct(r.accuracy)} |",
        f"| Category accuracy (answered) | {pct(r.category_correct / max(1, r.answered))} |",
        "",
        "## Confusion (rows: answer key, columns: dashboard)",
        "",
        "| | needs_you | fyi | noise |",
        "|---|---|---|---|",
    ]
    for t in BUCKETS:
        lines.append(f"| {t} | " + " | ".join(str(r.confusion.get((t, p), 0)) for p in BUCKETS) + " |")
    lines += ["", "## Tricky cases", "", "| Case | Expected | Got | |", "|---|---|---|---|"]
    for note, t, p, ok in r.tricky:
        lines.append(f"| {note} | {t} | {p} | {'✓' if ok else '✗'} |")
    if r.misses:
        lines += ["", "## Every miss", "", "| Email | Expected | Got |", "|---|---|---|"]
        for mid, subject, t, p, _ in r.misses:
            lines.append(f"| {mid}: {subject} | {t} | {p} |")
    return "\n".join(lines) + "\n"
